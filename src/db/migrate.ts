export async function runMigrations(): Promise<void> {
  const db = await getDatabase();
  db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL)');
  for (const migration of MIGRATIONS) {
    const name = migration.trim().split('\n')[0].slice(0, 100);
    const exists = db.exec(`SELECT 1 FROM schema_migrations WHERE name = '${name}'`);
    if (exists.length === 0 || exists[0].values.length === 0) {
      db.exec(migration);
      db.run(`INSERT INTO schema_migrations (name, applied_at) VALUES (?, ?)`, [name, new Date().toISOString()]);
    }
  }
  saveDatabase();
}